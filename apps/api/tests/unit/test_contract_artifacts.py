"""[SPEC-2201] The generated contract artefacts derive from `api/openapi.yaml` only.

These tests are the freshness guarantee of `pnpm py:contract:check`: they fail if the contract gains
an operation, a policy flag or a schema the committed table does not reflect (ADR-2012).
"""

import json
from pathlib import Path

import pytest
from learny_api.generated.models import MeGetOutput
from learny_api.generated.routes import ROUTES, ROUTES_BY_ID, RouteSpec
from pydantic import BaseModel

pytestmark = pytest.mark.spec("SPEC-2201")

ROOT = Path(__file__).resolve().parents[4]
GENERATED = ROOT / "apps" / "api" / "src" / "learny_api" / "generated"
ARTEFACTS = ("__init__.py", "models.py", "routes.py")


def test_every_operation_of_the_inventory_has_a_route() -> None:
    inventory = json.loads((ROOT / "api" / "inventory.json").read_text(encoding="utf-8"))
    operation_ids = {str(operation["id"]) for operation in inventory["operations"]}

    assert len(ROUTES) == len(operation_ids)
    assert {route.id for route in ROUTES} == operation_ids
    assert len(ROUTES_BY_ID) == len(ROUTES)


def test_every_route_carries_the_whole_policy() -> None:
    for route in ROUTES:
        assert isinstance(route, RouteSpec)
        assert route.auth in {"user", "public"}, route.id
        assert route.rate_limit in {"default", "ai", "auth", "none"}, route.id
        assert route.validation_status in {400, 422}, route.id
        assert 200 <= route.success_status <= 302, route.id
        assert route.method in {"GET", "POST", "PUT", "PATCH", "DELETE"}, route.id
        assert route.output is None or route.success_status not in {204, 302}, route.id


def test_the_models_of_the_routes_are_pydantic_models() -> None:
    for route in ROUTES:
        for model in (route.params, route.query, route.body, route.output):
            assert model is None or (isinstance(model, type) and issubclass(model, BaseModel)), route.id


def test_a_static_segment_is_registered_before_a_parameter() -> None:
    position = {route.id: index for index, route in enumerate(ROUTES)}
    pairs = 0
    for static in ROUTES:
        left = static.path.split("/")
        for other in ROUTES:
            right = other.path.split("/")
            if len(left) != len(right):
                continue
            differing = [index for index in range(len(left)) if left[index] != right[index]]
            if len(differing) != 1:
                continue
            index = differing[0]
            if left[index].startswith("{") or not right[index].startswith("{"):
                continue
            assert position[static.id] < position[other.id], (static.id, other.id)
            pairs += 1
    assert pairs > 0


def test_the_generated_files_say_they_are_generated() -> None:
    for name in ARTEFACTS:
        text = (GENERATED / name).read_text(encoding="utf-8")
        assert "Generated by tools/contract/generate-py-contract.mjs" in text, name


def test_the_boundary_formats_stay_strings() -> None:
    text = (GENERATED / "models.py").read_text(encoding="utf-8")

    for forbidden in ("AwareDatetime", "EmailStr", "AnyUrl", "from uuid import UUID", "Decimal"):
        assert forbidden not in text, forbidden


def test_the_five_documented_operations_without_a_json_output() -> None:
    """SSE, redirects, an HTML page and the 204 of `formations.access` carry no output model."""
    assert {route.id for route in ROUTES if route.output is None} == {
        "auth.callback",
        "auth.magicLink",
        "auth.resend",
        "auth.signOut",
        "conversations.messages",
        "diagnostic.skip",
        "email.unsubscribe.page",
        "formations.access",
        "me.ai.credentials.delete",
        "me.deletion.cancel",
        "pushSubscriptions.delete",
        "resources.delete",
    }


def test_the_204_quirk_of_formations_access_is_kept() -> None:
    route = ROUTES_BY_ID["formations.access"]

    assert route.method == "GET"
    assert route.path == "/api/v1/formations/{fid}/access"
    assert route.success_status == 204
    assert route.output is None


def test_a_body_model_is_strict_where_the_contract_forbids_extra_keys() -> None:
    spec = MeGetOutput.model_config

    assert spec.get("extra") in {"forbid", None}
