interface ExerciseSeed {
  formationId: string;
  moduleId: string;
  notionId: string;
  exerciseId: string;
}

/**
 * Mockup-shaped SAP programme (module 3, notion 20 « Équilibre d’une pièce ») and the practice
 * exercise generated by the tutor fixture. Mastery 55 % and an application gap reproduce SCR-08.
 */
async function seedExercise(): Promise<ExerciseSeed> {
  const base = await serviceDb().transaction(async (tx) => {
    const programme = await createTestProgramme(tx, session.userId, {
      modules: 7,
      chaptersPerModule: 1,
      notionsPerChapter: 3,
      title: 'SAP S/4HANA Finance',
    });
    const moduleTitles = [
      'Fondamentaux de la comptabilité',
      'Devises et variantes d’exercice',
      'Comptabilité générale',
      'Module 4',
      'Module 5',
      'Module 6',
      'Module 7',
    ];
    for (const [index, moduleId] of programme.moduleIds.entries()) {
      await tx.execute(sql`
        update public.modules
        set title = ${moduleTitles[index] ?? `Module ${String(index + 1)}`},
            status = ${index < 2 ? 'validated' : index === 2 ? 'open' : 'locked'}::public.module_status
        where id = ${moduleId}::uuid
      `);
    }
    const notionId = programme.notionIds[6];
    const moduleId = programme.moduleIds[2];
    if (notionId === undefined || moduleId === undefined) throw new Error('programme SAP incomplet');
    await tx.execute(sql`
      update public.notions set label = 'Équilibre d’une pièce' where id = ${notionId}::uuid
    `);
    const course = await createTestCourse(tx, {
      ownerId: session.userId,
      moduleId,
      sectionsPerChapter: 1,
    });
    await tx.execute(sql`
      insert into public.notion_states (
        user_id, notion_id, fsrs, due_at, mastery, first_seen_at, last_seen_at, success_count,
        gap_nature, gap_detected_at, gap_evidence, in_review
      ) values (
        ${session.userId}::uuid,
        ${notionId}::uuid,
        ${JSON.stringify({
          due: NOW,
          stability: 1,
          difficulty: 5,
          elapsed_days: 0,
          scheduled_days: 1,
          reps: 1,
          lapses: 1,
          state: 2,
          last_review: NOW,
        })}::jsonb,
        ${NOW}::timestamptz,
        55,
        ${NOW}::timestamptz,
        ${NOW}::timestamptz,
        1,
        'application',
        ${NOW}::timestamptz,
        'définition juste, mais exercice de saisie échoué.',
        true
      )
    `);
    await tx.execute(sql`
      update public.profiles
      set current_formation_id = ${programme.formationId}::uuid
      where id = ${session.userId}::uuid
    `);
    return {
      formationId: programme.formationId,
      moduleId,
      notionId,
      courseId: course.courseId,
    };
  });

  const ctx = createServiceContext({
    userId: session.userId,
    email: session.email,
    requestId: crypto.randomUUID(),
    clock: { now: () => new Date(NOW) },
  });
  const ensured = await ensurePracticeExercise(ctx, base.notionId);
  if (!ensured.ok) throw new Error(ensured.error.code);
  return {
    formationId: base.formationId,
    moduleId: base.moduleId,
    notionId: base.notionId,
    exerciseId: ensured.value.exerciseId,
  };
}

function exerciseUrl(seed: ExerciseSeed): string {
  return `/formations/${seed.formationId}/modules/${seed.moduleId}/exercices/${seed.exerciseId}`;
}

async function fillRow(
  page: import('@playwright/test').Page,
  row: number,
  cle: string,
  compte: string,
  montant: string,
): Promise<void> {
  await page.getByTestId(`exercise-cell-${String(row)}-cle`).selectOption(cle);
  await page.getByTestId(`exercise-cell-${String(row)}-compte`).selectOption(compte);
  await page.getByTestId(`exercise-cell-${String(row)}-montant`).fill(montant);
}

test('résout un exercice structuré @SPEC-613', async ({
  page,
  axeCheck,
  captureEvidence,
  consoleErrors,
}) => {
  const seed = await seedExercise();
  await page.goto(exerciseUrl(seed));

  await expect(page.getByRole('heading', { level: 1, name: 'Saisir une pièce équilibrée' })).toBeVisible();
  await expect(page.getByTestId('exercise-table-state')).toHaveText('Pas encore de montant');
  await page.getByTestId('exercise-field-type').selectOption('SA');
  await page.getByTestId('exercise-field-date').fill('12/11/2026');
  await fillRow(page, 0, '40', '606400', '100');
  await fillRow(page, 1, '50', '512000', '120');

  // CA-1 — an unbalanced piece is refused before any tutor call.
  await page.getByTestId('exercise-submit').click();
  await expect(page.getByTestId('exercise-message')).toContainText('Écart : 20 €');
  await expect(page.getByTestId('exercise-feedback')).toHaveCount(0);

  await page.getByTestId('exercise-cell-0-montant').fill('120');
  await expect(page.getByTestId('exercise-table-state')).toHaveText('✓ Pièce équilibrée');

  // CA-2 — two hints reduce the maximum from 10 to 8; the third button is disabled.
  await page.getByTestId('exercise-hint').click();
  await expect(page.getByTestId('exercise-hint-box')).toContainText('Indice 1');
  await page.getByTestId('exercise-hint').click();
  await expect(page.getByTestId('exercise-hint-box')).toContainText('Indice 2');
  await expect(page.getByTestId('exercise-hint')).toBeDisabled();
  await expect(page.getByTestId('exercise-scale-title')).toHaveText('Barème · 8 points');

  await page.getByTestId('exercise-explanation').fill(
    'Tout montant débité est crédité ailleurs : le débit doit donc égaler le crédit.',
  );
  await page.getByTestId('exercise-submit').click();
  await expect(page.getByTestId('exercise-feedback')).toBeVisible();
  await expect(page.getByTestId('exercise-score')).toHaveText('8 / 10');
  await expect(page.getByTestId('exercise-criterion')).toHaveCount(5);
  await expect(page.getByTestId('exercise-verdict')).toHaveText('Réussi');

  // CA-3 — a reload finds the production, the correction and the mastery before/after.
  await page.reload();
  await expect(page.getByTestId('exercise-feedback')).toBeVisible();
  await expect(page.getByTestId('exercise-score')).toHaveText('8 / 10');
  await expect(page.getByTestId('exercise-cell-0-montant')).toHaveValue('120');
  await expect(page.getByTestId('exercise-cell-0-montant')).toBeDisabled();

  expect(consoleErrors.filter((entry) => !entry.includes('422'))).toEqual([]);
  await axeCheck();
  await captureEvidence('spec-613-exercice-resolu');
});

test('reprend une production @SPEC-613', async ({ page, axeCheck, captureEvidence }) => {
  const seed = await seedExercise();
  await page.goto(exerciseUrl(seed));
  await page.getByTestId('exercise-field-type').selectOption('SA');
  await page.getByTestId('exercise-field-date').fill('12/11/2026');
  await fillRow(page, 0, '40', '606400', '120');
  await fillRow(page, 1, '50', '512000', '120');
  await page.getByTestId('exercise-explanation').fill('Brouillon conservé avant la soumission.');
  await expect(page.getByTestId('exercise-draft-status')).toHaveText('Brouillon enregistré');

  await page.reload();
  await expect(page.getByTestId('exercise-cell-0-cle')).toHaveValue('40');
  await expect(page.getByTestId('exercise-cell-1-compte')).toHaveValue('512000');
  await expect(page.getByTestId('exercise-explanation')).toHaveValue(
    'Brouillon conservé avant la soumission.',
  );
  await expect(page.getByTestId('exercise-feedback')).toHaveCount(0);
  await axeCheck();
  await captureEvidence('spec-613-reprise-brouillon');
});

test('refuse l’exercice d’un autre apprenant @SPEC-613', async ({ browser, baseURL }) => {
  const seed = await seedExercise();
  const stranger = await createTestSession();
  const context = await browser.newContext(baseURL === undefined ? {} : { baseURL });
  try {
    await context.addCookies(
      stranger.cookies.map((cookie) => ({ ...cookie, url: baseURL ?? 'http://127.0.0.1:3100' })),
    );
    const page = await context.newPage();
    const response = await page.goto(exerciseUrl(seed));
    expect(response?.status()).toBe(404);
    await expect(page.getByTestId('system-not-found')).toBeVisible();
  } finally {
    await context.close();
    await deleteTestSession(stranger);
  }
});

async function compareContent(
  page: import('@playwright/test').Page,
  referenceName: string,
  reference: { x: number; y: number; width: number; height: number },
  testInfo: import('@playwright/test').TestInfo,
  name: string,
): Promise<number> {
  const content = page.getByTestId('exercise-content');
  const actual = await content.screenshot({ animations: 'disabled', scale: 'css' });
  const comparison = compareWithReferenceRegion(
    actual,
    `${REFERENCE_DIR}${referenceName}`,
    reference,
    testInfo.outputPath('visual'),
    name,
  );
  await testInfo.attach(`${name}-side-by-side`, {
    path: comparison.sideBySidePath,
    contentType: 'image/png',
  });
  await testInfo.attach(`${name}-diff`, { path: comparison.diffPath, contentType: 'image/png' });
  testInfo.annotations.push({
    type: 'mockup-diff-ratio',
    description: `${name}:${comparison.ratio.toFixed(4)}`,
  });
  return comparison.ratio;
}

test('conformité SPEC-613 @SPEC-613 @visual', async ({ page, axeCheck }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const seed = await seedExercise();
  await page.setViewportSize({ width: 1600, height: 1088 });
  await page.goto(exerciseUrl(seed));
  await expect(page.getByTestId('exercise-table')).toBeVisible();

  await expectTokens(page, {
    body: { 'background-color': colors.canvas, color: colors.ink },
    '[data-testid="exercise-brief"]': {
      'background-color': colors.ink,
      'border-radius': '21.6px',
    },
    '[data-testid="exercise-table"] select': {
      'background-color': colors.surface,
      'border-color': colors['border-strong'],
      'border-radius': '10.8px',
    },
    '[data-testid="exercise-submit"]': {
      'background-color': colors.ink,
      color: colors.white,
      'border-radius': '12.6px',
    },
  });
  const ratio = await compareContent(
    page,
    'SCR-08-base-desktop.png',
    REFERENCE_DESKTOP,
    testInfo,
    'spec-613-desktop',
  );
  expect(ratio, 'écart à la maquette desktop').toBeLessThanOrEqual(MOCKUP_MAX_DIFF_RATIO);

  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(exerciseUrl(seed));
  await expect(page.getByTestId('exercise-table')).toBeVisible();
  await expectScreenshotBaseline(page, 'SCR-08-desktop.png', { fullPage: true });
  await axeCheck();
});

