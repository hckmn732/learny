// SPEC-2201 — generates the Python contract artefacts from `api/openapi.yaml` (ADR-2012).
//
// Two files are produced, both committed and never edited by hand:
//   apps/api-py/src/learny_api/generated/models.py  Pydantic DTOs (datamodel-codegen, spikes.md §F)
//   apps/api-py/src/learny_api/generated/routes.py  RouteSpec table built from the `x-learny` policy
// `--check` regenerates into a temporary directory and compares, like `sdk:check` (ADR-2012).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import YAML from 'yaml';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SOURCE = join(ROOT, 'api', 'openapi.yaml');
const GENERATED = join(ROOT, 'apps', 'api-py', 'src', 'learny_api', 'generated');
const MODELS = join(GENERATED, 'models.py');
const ROUTES = join(GENERATED, 'routes.py');

const HEADER =
  '# Generated by tools/contract/generate-py-contract.mjs from api/openapi.yaml: do not edit.';

// Formats stay plain strings at the boundary so nothing is re-serialised (spikes.md §F, ADR-2012).
const FORMATS = ['date-time', 'date', 'uuid', 'email', 'uri', 'time', 'duration'];
const TYPE_MAPPINGS = [
  ...FORMATS.map((format) => `string+${format}=string`),
  // A few contract schemas carry a format without an explicit `type`: they stay strings too.
  ...FORMATS.map((format) => `${format}=string`),
];

function codegenBinary() {
  const local = join(ROOT, '.venv', 'bin', 'datamodel-codegen');
  if (existsSync(local)) return local;
  const windows = join(ROOT, '.venv', 'Scripts', 'datamodel-codegen.exe');
  return existsSync(windows) ? windows : 'datamodel-codegen';
}

function generateModels(output) {
  const args = [
    '--input',
    SOURCE,
    '--input-file-type',
    'openapi',
    '--output',
    output,
    '--output-model-type',
    'pydantic_v2.BaseModel',
    '--target-python-version',
    '3.13',
    '--collapse-root-models',
    '--disable-timestamp',
    '--formatters',
    'builtin',
    '--use-standard-collections',
    '--use-union-operator',
    '--custom-file-header',
    HEADER,
    '--custom-file-header-mode',
    'replace',
    '--type-mappings',
    ...TYPE_MAPPINGS,
  ];
  execFileSync(codegenBinary(), args, { cwd: ROOT, stdio: ['ignore', 'ignore', 'inherit'] });
}

/** `attempts.submit` -> `AttemptsSubmit`; `dev.sdd.spec-103.demo` -> `DevSddSpec103Demo`. */
export function pascalName(routeId) {
  return routeId
    .split(/[^A-Za-z0-9]+/)
    .filter((part) => part !== '')
    .map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
    .join('');
}

function modelRef(document, schema) {
  const ref = schema?.$ref;
  if (typeof ref !== 'string') return null;
  const name = ref.slice(ref.lastIndexOf('/') + 1);
  if (document.components?.schemas?.[name] === undefined) return null;
  return name;
}

function routeOf(document, path, method) {
  const policy = document.paths[path][method]['x-learny'];
  if (policy === undefined) throw new Error(`x-learny missing on ${method.toUpperCase()} ${path}`);
  const base = pascalName(policy.id);
  const schemas = document.components?.schemas ?? {};
  const named = (suffix) => (schemas[`${base}${suffix}`] === undefined ? null : `${base}${suffix}`);
  const operation = document.paths[path][method];
  const body = modelRef(document, operation.requestBody?.content?.['application/json']?.schema);
  const success = modelRef(
    document,
    operation.responses?.[String(policy.successStatus)]?.content?.['application/json']?.schema,
  );
  return {
    id: policy.id,
    method: method.toUpperCase(),
    path,
    auth: policy.auth,
    rateLimit: policy.rateLimit,
    idempotent: policy.idempotent === true,
    requiresIdempotencyKey: policy.requiresIdempotencyKey === true,
    freshAuth: policy.freshAuth === true,
    legalAcceptance: policy.legalAcceptance === true,
    validationStatus: policy.validationStatus,
    successStatus: policy.successStatus,
    params: named('Params'),
    query: named('Query'),
    body: body === null ? null : modelRef(document, { $ref: `#/components/schemas/${body}` }),
    output:
      success === null ? null : modelRef(document, { $ref: `#/components/schemas/${success}` }),
    segments: path.split('/').slice(1),
  };
}

/** Static segments first at every depth, like the Hono router: `/formations/access` before `/formations/{fid}`. */
function specificity(route) {
  return route.segments.map((segment) => (segment.startsWith('{') ? 1 : 0));
}

function compareRoutes(left, right) {
  const a = specificity(left);
  const b = specificity(right);
  for (let index = 0; index < Math.min(a.length, b.length); index += 1) {
    if (a[index] !== b[index]) return a[index] - b[index];
  }
  return a.length - b.length;
}

export function readRoutes(source = SOURCE) {
  const document = YAML.parse(readFileSync(source, 'utf8'));
  const routes = [];
  for (const [path, item] of Object.entries(document.paths ?? {})) {
    for (const method of Object.keys(item)) {
      if (method === 'parameters' || method === 'summary' || method === 'description') continue;
      routes.push(routeOf(document, path, method));
    }
  }
  routes.sort(compareRoutes);
  const seen = new Set();
  for (const route of routes) {
    if (seen.has(route.id)) throw new Error(`duplicate route id ${route.id}`);
    seen.add(route.id);
  }
  return routes;
}

function pythonString(value) {
  return `'${String(value).replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

export function renderRoutes(routes) {
  const models = [
    ...new Set(routes.flatMap((r) => [r.params, r.query, r.body, r.output]).filter(Boolean)),
  ].sort();
  const lines = [
    HEADER,
    '',
    '"""Route table of the contract: one `RouteSpec` per operation of `api/openapi.yaml` (ADR-2012)."""',
    '',
    'from __future__ import annotations',
    '',
    'from dataclasses import dataclass',
    'from typing import Literal',
    '',
    'from pydantic import BaseModel',
    '',
  ];
  if (models.length > 0) {
    lines.push('from learny_api.generated.models import (');
    for (const model of models) lines.push(`    ${model},`);
    lines.push(')', '');
  }
  lines.push(
    'AuthKind = Literal["user", "public"]',
    'RateLimitProfile = Literal["default", "ai", "auth", "none"]',
    '',
    '',
    '@dataclass(frozen=True, slots=True)',
    'class RouteSpec:',
    '    """Everything the pipeline needs to know about one operation (00-conventions section 6)."""',
    '',
    '    id: str',
    '    method: str',
    '    path: str',
    '    auth: AuthKind',
    '    rate_limit: RateLimitProfile',
    '    idempotent: bool',
    '    requires_idempotency_key: bool',
    '    fresh_auth: bool',
    '    legal_acceptance: bool',
    '    validation_status: int',
    '    success_status: int',
    '    params: type[BaseModel] | None',
    '    query: type[BaseModel] | None',
    '    body: type[BaseModel] | None',
    '    output: type[BaseModel] | None',
    '',
    '',
    '# Static segments sort first at every depth: FastAPI matches in registration order.',
    'ROUTES: tuple[RouteSpec, ...] = (',
  );
  for (const route of routes) {
    const model = (name) => (name === null ? 'None' : name);
    lines.push(
      '    RouteSpec(',
      `        id=${pythonString(route.id)},`,
      `        method=${pythonString(route.method)},`,
      `        path=${pythonString(route.path)},`,
      `        auth=${pythonString(route.auth)},`,
      `        rate_limit=${pythonString(route.rateLimit)},`,
      `        idempotent=${route.idempotent ? 'True' : 'False'},`,
      `        requires_idempotency_key=${route.requiresIdempotencyKey ? 'True' : 'False'},`,
      `        fresh_auth=${route.freshAuth ? 'True' : 'False'},`,
      `        legal_acceptance=${route.legalAcceptance ? 'True' : 'False'},`,
      `        validation_status=${route.validationStatus},`,
      `        success_status=${route.successStatus},`,
      `        params=${model(route.params)},`,
      `        query=${model(route.query)},`,
      `        body=${model(route.body)},`,
      `        output=${model(route.output)},`,
      '    ),',
    );
  }
  lines.push(
    ')',
    '',
    'ROUTES_BY_ID: dict[str, RouteSpec] = {route.id: route for route in ROUTES}',
    '',
  );
  return lines.join('\n');
}

function write(directory) {
  const models = join(directory, 'models.py');
  generateModels(models);
  const routes = join(directory, 'routes.py');
  writeFileSync(routes, renderRoutes(readRoutes()), 'utf8');
  writeFileSync(
    join(directory, '__init__.py'),
    `${HEADER}\n\n"""Generated contract artefacts; regenerate with pnpm py:contract:generate."""\n`,
    'utf8',
  );
}

export function main(argv = process.argv.slice(2)) {
  if (argv.includes('--check')) {
    const directory = mkdtempSync(join(tmpdir(), 'learny-py-contract-'));
    try {
      write(directory);
      const stale = ['models.py', 'routes.py', '__init__.py'].filter((name) => {
        const committed = join(GENERATED, name);
        return (
          !existsSync(committed) ||
          readFileSync(committed, 'utf8') !== readFileSync(join(directory, name), 'utf8')
        );
      });
      if (stale.length > 0) {
        console.error(
          `✖ artefacts Python du contrat périmés (${stale.join(', ')}) : lancer pnpm py:contract:generate`,
        );
        process.exitCode = 1;
        return;
      }
      console.log('✔ artefacts Python du contrat à jour');
    } finally {
      rmSync(directory, { recursive: true, force: true });
    }
    return;
  }
  mkdirSync(GENERATED, { recursive: true });
  write(GENERATED);
  console.log(`✔ ${MODELS}`);
  console.log(`✔ ${ROUTES}`);
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === resolve(process.argv[1]))
  main();
