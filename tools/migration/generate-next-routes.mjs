const REGEX_PREFIX = '(,=:[!&|?{};+-*%<>~^';
const PAIRS = { '(': ')', '{': '}', '[': ']' };

/** Index just after the bracket closing `text[openIndex]` (strings, comments and regex aware). */
function findClosing(text, openIndex) {
  const stack = [text[openIndex]];
  let index = openIndex + 1;
  let previous = text[openIndex];
  while (index < text.length) {
    const char = text[index];
    if (char === '/' && text[index + 1] === '/') {
      const newline = text.indexOf('\n', index);
      if (newline < 0) return -1;
      index = newline + 1;
      continue;
    }
    if (char === '/' && text[index + 1] === '*') {
      const end = text.indexOf('*/', index + 2);
      if (end < 0) return -1;
      index = end + 2;
      continue;
    }
    if (char === "'" || char === '"' || char === '`') {
      const quote = char;
      index += 1;
      while (index < text.length && text[index] !== quote) {
        if (text[index] === '\\') index += 1;
        if (quote === '`' && text[index] === '$' && text[index + 1] === '{') {
          index = findClosing(text, index + 1) + 1;
          continue;
        }
        index += 1;
      }
      index += 1;
      previous = quote;
      continue;
    }
    if (char === '/' && REGEX_PREFIX.includes(previous)) {
      index += 1;
      let inClass = false;
      while (index < text.length) {
        if (text[index] === '\\') {
          index += 2;
          continue;
        }
        if (text[index] === '[') inClass = true;
        else if (text[index] === ']') inClass = false;
        else if (text[index] === '/' && !inClass) break;
        index += 1;
      }
      index += 1;
      previous = '/';
      continue;
    }
    if (PAIRS[char] !== undefined) {
      stack.push(char);
      index += 1;
      previous = char;
      continue;
    }
    if (char === ')' || char === '}' || char === ']') {
      stack.pop();
      if (stack.length === 0) return index;
      index += 1;
      previous = char;
      continue;
    }
    if (!/\s/.test(char)) previous = char;
    index += 1;
  }
  return -1;
}

function splitTopLevel(text, openIndex) {
  const end = findClosing(text, openIndex);
  const parts = [];
  let start = openIndex + 1;
  let index = openIndex + 1;
  let depth = 0;
  while (index < end) {
    const char = text[index];
    if (char === '/' && text[index + 1] === '/') {
      const newline = text.indexOf('\n', index);
      index = newline < 0 ? end : newline + 1;
      continue;
    }
    if (char === "'" || char === '"' || char === '`') {
      const quote = char;
      index += 1;
      while (index < end && text[index] !== quote) {
        if (text[index] === '\\') index += 2;
        else if (quote === '`' && text[index] === '$' && text[index + 1] === '{') {
          index = findClosing(text, index + 1) + 1;
        } else index += 1;
      }
      index += 1;
      continue;
    }
    if (PAIRS[char] !== undefined) depth += 1;
    else if (char === ')' || char === '}' || char === ']') depth -= 1;
    else if (char === ',' && depth === 0) {
      parts.push(text.slice(start, index));
      start = index + 1;
    }
    index += 1;
  }
  parts.push(text.slice(start, end));
  return parts.map((part) => part.replace(/\/\/[^\n]*/g, '').trim()).filter((part) => part !== '');
}

/** Everything the generator needs from `packages/contracts`: key → method + path (source analysis). */
export function readRegistry(root = ROOT) {
  const directory = path.join(root, 'packages', 'contracts', 'src');
  const read = (name) => fs.readFileSync(path.join(directory, `${name}.ts`), 'utf8');
  const routesSource = read('routes');
  const modules = new Map();
  for (const match of routesSource.matchAll(/from '\.\/([\w-]+)'/g)) {
    modules.set(match[1], read(match[1]));
  }
  const objects = new Map();
  for (const [moduleName, text] of modules) {
    for (const match of text.matchAll(/export const (\w+)\s*=\s*\{/g)) {
      if (!objects.has(match[1])) objects.set(match[1], { moduleName, text });
    }
  }
  const registry = new Map();
  const expand = (objectName, seen = new Set()) => {
    if (seen.has(objectName)) return [];
    seen.add(objectName);
    const owner = objects.get(objectName);
    if (owner === undefined) return [];
    const marker = new RegExp(`export const ${objectName}\\s*=\\s*\\{`);
    const match = marker.exec(owner.text);
    if (match === null) return [];
    const open = match.index + match[0].length - 1;
    const entries = [];
    for (const member of splitTopLevel(owner.text, open)) {
      if (member.startsWith('...')) {
        entries.push(...expand(member.slice(3).trim(), seen));
        continue;
      }
      const inline = /^(\w+):\s*defineRoute\(/.exec(member);
      if (inline !== null) {
        const offset = member.indexOf('defineRoute(') + 'defineRoute('.length;
        entries.push({
          key: inline[1],
          body: member.slice(offset, findClosing(member, offset - 1)),
        });
        continue;
      }
      if (/^\w+$/.test(member)) {
        const start = owner.text.search(new RegExp(`export const ${member}[ =]`));
        if (start < 0) continue;
        const callOpen = owner.text.indexOf('defineRoute(', start);
        if (callOpen < 0) continue;
        entries.push({
          key: member,
          body: owner.text.slice(
            callOpen + 'defineRoute('.length,
            findClosing(owner.text, callOpen + 'defineRoute'.length),
          ),
        });
      }
    }
    return entries;
  };

  const routesObject = /export const ROUTES = \{([\s\S]*?)\} as const;/.exec(routesSource);
  for (const spread of [...routesObject[1].matchAll(/\.\.\.(\w+)/g)].map((match) => match[1])) {
    for (const entry of expand(spread)) {
      const method = /method: '(\w+)'/.exec(entry.body)?.[1];
      const routePath = /path: '([^']+)'/.exec(entry.body)?.[1];
      if (method !== undefined && routePath !== undefined) {
        registry.set(entry.key, { method, path: routePath });
      }
    }
  }
  return registry;
}

/** Special handlers read from `src/special/manifest.ts` (commit-time data of the package). */
export function readSpecials(root = ROOT) {
  const source = fs.readFileSync(
    path.join(root, 'packages', 'api-routes', 'src', 'special', 'manifest.ts'),
    'utf8',
  );
  const entries = [];
  // One triple per handler: `{ key: '…', method: '…', path: '…' },`; Prettier may split the line,
  // so the separator is any whitespace.
  for (const match of source.matchAll(/key: '([^']+)',\s*method: '([^']+)',\s*path: '([^']+)'/g)) {
    entries.push({ key: match[1], method: match[2], path: match[3] });
  }
  return entries;
}

/** `api/v1/formations/:fid` → `api/v1/formations/[fid]`, `_dev` → `%5Fdev`. */
export function filePathOf(routePath) {
  const segments = routePath
    .split('/')
    .filter((segment) => segment !== '')
    .map((segment) => {
      if (segment.startsWith(':')) return `[${segment.slice(1)}]`;
      return segment === '_dev' ? '%5Fdev' : segment;
    });
  return `${segments.join('/')}/route.ts`;
}

const METHODS_OF_ALL = ['GET', 'POST', 'PUT'];

/** Plans every file: path → `{ content, methods, keys }`, derived from the two tables. */
export function plannedFiles(root = ROOT) {
  const registry = readRegistry(root);
  const specials = readSpecials(root);
  const planned = new Map();
  const duplicates = [];
  const seen = new Map();

  const add = (key, method, routePath, special) => {
    const id = `${method} ${routePath}`;
    if (seen.has(id)) duplicates.push(id);
    seen.set(id, key);
    const file = filePathOf(routePath);
    const entry = planned.get(file) ?? { methods: new Map(), keys: [] };
    for (const verb of method === 'ALL' ? METHODS_OF_ALL : [method]) {
      entry.methods.set(verb, { key, special });
    }
    entry.keys.push(key);
    planned.set(file, entry);
  };

  for (const [key, route] of registry) {
    if (specials.some((entry) => entry.key === key)) continue;
    add(key, route.method, route.path, false);
  }
  for (const entry of specials) {
    add(entry.key, entry.method, entry.path, true);
  }

  const files = new Map();
  for (const [relative, entry] of [...planned].sort(([left], [right]) =>
    left.localeCompare(right),
  )) {
    files.set(relative, {
      content: renderFile(relative, entry.methods),
      methods: [...entry.methods.keys()].sort(),
      keys: entry.keys,
    });
  }
  return { files, duplicates, registry: registry.size, specials: specials.length };
}

/** One generated file: header, the two imports, segment options, one export per method. */
export function renderFile(relative, methods) {
  const directory = relative.split('/').slice(0, -1);
  const prefix = '../'.repeat(directory.length + 1);
  const special = [...methods.values()].some((entry) => entry.special);
  const options = SEGMENT_OPTIONS[relative] ?? {};
  const lines = [
    GENERATED_HEADER,
    `import { ${special ? 'nextSpecial' : 'nextRoute'} } from '${prefix}${NEXT_ROUTE_MODULE}';`,
    '',
    "export const dynamic = 'force-dynamic';",
  ];
  if (options.runtime !== undefined) lines.push(`export const runtime = '${options.runtime}';`);
  if (options.maxDuration !== undefined)
    lines.push(`export const maxDuration = ${options.maxDuration};`);
  lines.push('');
  for (const [verb, entry] of [...methods].sort(([left], [right]) => left.localeCompare(right))) {
    lines.push(
      `export const ${verb} = ${entry.special ? 'nextSpecial' : 'nextRoute'}('${entry.key}');`,
    );
  }
  return `${lines.join('\n')}\n`;
}

/** Scans the tree: path → `{ content, methods }` for every existing route.ts under app/api. */
/** Expected files, in the shape the coverage table uses (path relative to apps/web/app). */
export function expectedRouteFiles(root = ROOT) {
  const { files } = plannedFiles(root);
  return [...files].map(([relative, file]) => ({ path: relative, methods: file.methods }));
}

export function scanGenerated(root = ROOT) {
  const found = new Map();
  const walk = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const full = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        walk(full);
        continue;
      }
      if (entry.name !== 'route.ts') continue;
      const relative = path
        .relative(path.join(root, 'apps', 'web', 'app'), full)
        .split(path.sep)
        .join('/');
      const content = fs.readFileSync(full, 'utf8');
      const methods = [
        ...content.matchAll(/^export const (GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS) = /gm),
      ].map((match) => match[1]);
      found.set(relative, { content, methods });
    }
  };
  const apiDirectory = path.join(root, API_ROOT);
  if (fs.existsSync(apiDirectory)) walk(apiDirectory);
  return found;
}

/**
 * SPEC-1004 EF-4 — drift report. Fails when the tree differs from the tables (`drift`), when a
 * route.ts is covered by no table (`orphans`), when a table entry has no file (`missing`) or when
 * two entries share one method + path (`duplicates`).
 */
export function check(root = ROOT) {
  const { files, duplicates } = plannedFiles(root);
  const actual = scanGenerated(root);
  const drift = [];
  const missing = [];
  for (const [relative, planned] of files) {
    const found = actual.get(relative);
    if (found === undefined) {
      missing.push(relative);
      continue;
    }
    if (found.content !== planned.content) drift.push(relative);
  }
  const orphans = [...actual.keys()].filter((relative) => !files.has(relative));
  return { drift, missing, orphans, duplicates, planned: files.size, present: actual.size };
}

function write(root = ROOT) {
  const { files, duplicates } = plannedFiles(root);
  for (const [relative, planned] of files) {
    const full = path.join(root, 'apps', 'web', 'app', relative);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, planned.content);
  }
  // A file that no table describes would be an orphan: the generator removes it (EF-4).
  const removed = [];
  for (const relative of scanGenerated(root).keys()) {
    if (files.has(relative)) continue;
    fs.rmSync(path.join(root, 'apps', 'web', 'app', relative));
    removed.push(relative);
  }
  return { written: files.size, removed, duplicates };
}

/** CLI: `--check` reports and fails, no argument regenerates the tree. */
export function main(argv = process.argv.slice(2), root = ROOT) {
  if (argv.includes('--check')) {
    const report = check(root);
    const problems = [
      ...report.drift.map((file) => `dérive : ${file}`),
      ...report.missing.map((file) => `fichier absent : ${file}`),
      ...report.orphans.map((file) => `fichier orphelin : ${file}`),
      ...report.duplicates.map((id) => `doublon : ${id}`),
    ];
    console.log(
      `Routes Next : ${String(report.present)} fichiers présents, ${String(report.planned)} attendus.`,
    );
    for (const problem of problems) console.error(problem);
    if (problems.length > 0) {
      console.error('pnpm migration:routes (régénère les fichiers depuis les tables).');
      process.exitCode = 1;
    } else {
      console.log('Aucune dérive (SPEC-1004 EF-4).');
    }
    return;
  }
  const result = write(root);
  console.log(`Routes Next régénérées : ${String(result.written)} fichiers.`);
  for (const file of result.removed) console.log(`supprimé (orphelin) : ${file}`);
  for (const id of result.duplicates) console.error(`doublon : ${id}`);
  if (result.duplicates.length > 0) process.exitCode = 1;
}

const entry = process.argv[1] === undefined ? null : pathToFileURL(process.argv[1]).href;
if (entry !== null && fileURLToPath(entry) === fileURLToPath(import.meta.url)) main();
