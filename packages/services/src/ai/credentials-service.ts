// Personal AI credentials (SPEC-505 ET-2, EF-1 to EF-6, BR-IA-02 to BR-IA-04).
// Creation encrypts at rest with AES-256-GCM and a per-row AAD; listing only projects the mask and
// the region flag; deletion removes the task assignments before the row. No function of this
// module returns, logs or throws a plaintext key.
import { randomUUID } from 'node:crypto';

import { and, asc, eq, sql } from 'drizzle-orm';

import {
  AiCredentialCreateBody,
  CREDENTIAL_LIMIT,
  CREDENTIAL_LIMIT_MESSAGE,
  type CredentialDto,
} from '@learny/contracts';
import { AppError, type Result } from '@learny/core';
import { assertPublicUrl } from '@learny/core/net';
import {
  aiCredentials,
  aiTaskModels,
  credentialStatusSchema,
  type AiCredential,
  type AiProviderValue,
  type CredentialStatusValue,
} from '@learny/db';
import { providerRegion } from '@learny/llm';
import {
  credentialAad,
  encryptSecret,
  keyFingerprint,
  keyLast4Of,
  keyPrefixOf,
  loadKeyring,
  maskKey,
  sameFingerprint,
} from '@learny/llm/credentials';

import type { ServiceContext } from '../context';
import { requireUser, toResult } from '../resources/result';

export type CreateCredentialInput = AiCredentialCreateBody;
export type QualificationReport = Record<string, unknown>;

/** `ALLOW_LOCAL_MODELS` is a raw boolean string of the server environment (default false). */
export function localModelsAllowed(
  env: Readonly<Record<string, string | undefined>> = process.env,
): boolean {
  return env.ALLOW_LOCAL_MODELS === 'true';
}

function validationFailure(errors: { path: string; message: string }[]): AppError {
  return new AppError('VALIDATION_FAILED', 'Les données envoyées sont invalides.', {
    status: 422,
    errors,
  });
}

function parseInput(input: unknown): AiCredentialCreateBody {
  const parsed = AiCredentialCreateBody.safeParse(input);
  if (parsed.success) return parsed.data;
  throw validationFailure(
    parsed.error.issues.map((issue) => ({
      path: ['body', ...issue.path.map(String)].join('.'),
      message: issue.message,
    })),
  );
}

function baseUrlFailure(message: string): AppError {
  return validationFailure([{ path: 'body.baseUrl', message }]);
}

/** EF-4 — one row to the only public shape, with the catalogue's region and note (CA-5). */
function toDto(row: AiCredential): CredentialDto {
  const region = providerRegion(row.provider);
  const qualification = row.qualification;
  const prefix = typeof qualification.keyPrefix === 'string' ? qualification.keyPrefix : '';
  return {
    id: row.id,
    provider: row.provider,
    providerLabel: region.providerLabel,
    label: row.label,
    baseUrl: row.baseUrl,
    modelIds: row.modelIds,
    keyMasked: row.keyLast4 === null ? null : maskKey(row.keyLast4, prefix),
    status: row.status,
    outsideEu: region.outsideEu,
    dataNote: region.dataNote,
    qualifiedAt: row.qualifiedAt === null ? null : row.qualifiedAt.toISOString(),
    createdAt: row.createdAt.toISOString(),
  };
}

async function checkEndpoint(provider: AiProviderValue, baseUrl: string): Promise<void> {
  if (provider === 'openai_compatible') {
    // EF-5 — a compatible endpoint is HTTPS and publicly routable (ADR-0159).
    let url: URL;
    try {
      url = new URL(baseUrl);
    } catch {
      throw baseUrlFailure('l’adresse doit être une URL https publique');
    }
    if (url.protocol !== 'https:') {
      throw baseUrlFailure('l’adresse d’un service compatible doit utiliser https');
    }
    await assertPublicUrl(baseUrl);
    return;
  }
  if (provider === 'local') {
    // ADR-0159 point 7 — the local-model exception allows a private host and any port.
    await assertPublicUrl(baseUrl, { allowPrivate: true });
  }
}

/**
 * EF-1, EF-6 — creates one credential. The UUID is generated by the application because the AAD
 * binds the ciphertext to it; the insert, the limit check and the duplicate check share one
 * transaction and one per-user advisory lock.
 */
export async function createCredential(
  ctx: ServiceContext,
  input: CreateCredentialInput,
): Promise<Result<CredentialDto>> {
  return toResult(async () => {
    const { userId, db } = requireUser(ctx);
    const parsed = parseInput(input);

    if (parsed.provider === 'local' && !localModelsAllowed()) {
      throw new AppError(
        'LOCAL_MODELS_DISABLED',
        'Les modèles locaux sont désactivés sur cette installation.',
        { status: 422 },
      );
    }
    if (parsed.baseUrl !== undefined) {
      await checkEndpoint(parsed.provider, parsed.baseUrl);
    }

    const ring = loadKeyring();
    const id = randomUUID();
    const aad = credentialAad(id, userId);
    const plain = parsed.apiKey;
    const encryptedKey = plain === undefined ? null : encryptSecret(plain, aad, ring.current);
    const last4 = plain === undefined ? null : keyLast4Of(plain);
    const prefix = plain === undefined ? '' : keyPrefixOf(plain);
    const fingerprint = plain === undefined ? null : keyFingerprint(plain, ring.current);
    const region = providerRegion(parsed.provider);
    const label = parsed.label ?? region.defaultLabel;

    return db.run(async (tx) => {
      // Serialises creations of one learner: the 10-credential cap and EF-6 cannot race.
      await tx.execute(sql`select pg_advisory_xact_lock(hashtext(${userId})::bigint)`);
      const rows = await tx
        .select({
          provider: aiCredentials.provider,
          baseUrl: aiCredentials.baseUrl,
          keyLast4: aiCredentials.keyLast4,
          qualification: aiCredentials.qualification,
        })
        .from(aiCredentials)
        .where(eq(aiCredentials.userId, userId));

      if (rows.length >= CREDENTIAL_LIMIT) {
        throw new AppError('CREDENTIAL_LIMIT_REACHED', CREDENTIAL_LIMIT_MESSAGE, { status: 422 });
      }

      if (plain !== undefined && fingerprint !== null) {
        for (const row of rows) {
          if (row.provider !== parsed.provider) continue;
          if (row.baseUrl !== (parsed.baseUrl ?? null)) continue;
          if (row.keyLast4 !== last4) continue;
          const stored = row.qualification.keyFingerprint;
          if (typeof stored === 'string' && sameFingerprint(stored, fingerprint)) {
            throw new AppError('CONFLICT', 'Cette clé est déjà enregistrée.', { status: 409 });
          }
        }
      }

      const inserted = await tx
        .insert(aiCredentials)
        .values({
          id,
          userId,
          provider: parsed.provider,
          label,
          baseUrl: parsed.baseUrl ?? null,
          modelIds: parsed.modelIds,
          encryptedKey,
          keyLast4: last4,
          status: 'untested',
          qualification:
            fingerprint === null ? {} : { keyFingerprint: fingerprint, keyPrefix: prefix },
          outsideEu: region.outsideEu,
          qualifiedAt: null,
          createdAt: ctx.clock.now(),
          updatedAt: ctx.clock.now(),
        })
        .returning();
      const row = inserted[0];
      if (row === undefined) throw new AppError('INTERNAL_ERROR', 'Identifiant non créé.');
      return toDto(row);
    });
  });
}

/** EF-2 — the learner's credentials, oldest first, at most ten. */
export async function listCredentials(ctx: ServiceContext): Promise<Result<CredentialDto[]>> {
  return toResult(async () => {
    const { userId, db } = requireUser(ctx);
    const rows = await db.run((tx) =>
      tx
        .select()
        .from(aiCredentials)
        .where(eq(aiCredentials.userId, userId))
        .orderBy(asc(aiCredentials.createdAt))
        .limit(CREDENTIAL_LIMIT),
    );
    return rows.map(toDto);
  });
}

/**
 * EF-3, CL-6 — removes the task assignments in the same transaction, then the credential. Another
 * learner's identifier is invisible under RLS and answers `NOT_FOUND` (CL-8).
 */
export async function deleteCredential(ctx: ServiceContext, id: string): Promise<Result<void>> {
  return toResult(async () => {
    const { userId, db } = requireUser(ctx);
    if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(id)) {
      throw new AppError('NOT_FOUND', 'Identifiant introuvable.');
    }
    await db.run(async (tx) => {
      await tx
        .delete(aiTaskModels)
        .where(and(eq(aiTaskModels.userId, userId), eq(aiTaskModels.credentialId, id)));
      const removed = await tx
        .delete(aiCredentials)
        .where(and(eq(aiCredentials.id, id), eq(aiCredentials.userId, userId)))
        .returning({ id: aiCredentials.id });
      if (removed[0] === undefined) {
        throw new AppError('NOT_FOUND', 'Identifiant introuvable.');
      }
    });
  });
}

/**
 * ET-2 — used by SPEC-506 after qualification and by SPEC-504 on `AI_KEY_INVALID`. The key
 * fingerprint and prefix are preserved; a report is merged, never exposed as is by the DTO.
 */
export async function markCredentialStatus(
  ctx: ServiceContext,
  id: string,
  status: CredentialStatusValue,
  report?: QualificationReport,
): Promise<Result<void>> {
  return toResult(async () => {
    const { userId, db } = requireUser(ctx);
    if (!credentialStatusSchema.safeParse(status).success) {
      throw new AppError('VALIDATION_FAILED', 'Statut de clé inconnu.', { status: 422 });
    }
    await db.run(async (tx) => {
      const rows = await tx
        .select({ qualification: aiCredentials.qualification })
        .from(aiCredentials)
        .where(and(eq(aiCredentials.id, id), eq(aiCredentials.userId, userId)))
        .limit(1);
      const row = rows[0];
      if (row === undefined) throw new AppError('NOT_FOUND', 'Identifiant introuvable.');
      await tx
        .update(aiCredentials)
        .set({
          status,
          qualifiedAt: status === 'qualified' ? ctx.clock.now() : null,
          qualification: { ...row.qualification, ...(report ?? {}) },
        })
        .where(and(eq(aiCredentials.id, id), eq(aiCredentials.userId, userId)));
    });
  });
}
