// Generates packages/ui/src/styles/theme.css from the typed tokens (SPEC-301, ET-2).
// Run with `pnpm --filter @learny/ui tokens:css`; the committed file must stay identical.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { colors } from '../src/tokens/colors';
import { controlHeightsPx, layout } from '../src/tokens/layout';
import { radiiPx, radiusFull } from '../src/tokens/radii';
import { shadows } from '../src/tokens/shadows';
import { px, spacingUnit } from '../src/tokens/spacing';
import {
  fontFamilies,
  fontSizesPx,
  fontWeights,
  letterSpacings,
  lineHeights,
} from '../src/tokens/typography';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const TARGET = path.join(ROOT, 'src', 'styles', 'theme.css');

/** CSS identifiers cannot contain an unescaped dot: `--text-11.5` is written `--text-11\.5`. */
function cssKey(value: string | number): string {
  return String(value).replaceAll('.', '\\.');
}

/**
 * Tailwind namespace reset: no default colour, text size, radius, shadow or font can be used
 * unless a token declares it (CL-3, CA-4). Declarations follow in the published token order.
 */
export function buildThemeCss(): string {
  const lines: string[] = [
    '/* Generated by packages/ui/scripts/build-theme.ts — do not edit. */',
    '@theme {',
    '  /* Closed namespaces: unknown utilities are not generated (SPEC-301, ET-2). */',
    '  --color-*: initial;',
    '  --text-*: initial;',
    '  --radius-*: initial;',
    '  --shadow-*: initial;',
    '  --font-*: initial;',
    '  --font-weight-*: initial;',
    '  --leading-*: initial;',
    '  --tracking-*: initial;',
    '',
    '  /* Interface colours (EF-2). */',
  ];

  for (const [name, value] of Object.entries(colors)) {
    lines.push(`  --color-${cssKey(name)}: ${value};`);
  }

  lines.push('', '  /* Text sizes, mockup pixels converted to rem (EF-4). */');
  for (const size of fontSizesPx) {
    lines.push(`  --text-${cssKey(size)}: ${px(size)};`);
  }

  lines.push('', '  /* Font weights and line heights (EF-4). */');
  for (const weight of fontWeights) {
    lines.push(`  --font-weight-${String(weight)}: ${String(weight)};`);
  }
  for (const height of lineHeights) {
    lines.push(`  --leading-${cssKey(height)}: ${String(height)};`);
  }
  for (const [name, value] of Object.entries(letterSpacings)) {
    lines.push(`  --tracking-${name}: ${value};`);
  }

  lines.push('', '  /* Radii (EF-6). */');
  for (const radius of radiiPx) {
    lines.push(`  --radius-${String(radius)}: ${px(radius)};`);
  }
  lines.push(`  --radius-full: ${radiusFull};`);

  lines.push('', '  /* Shadows (EF-7). */');
  for (const [name, value] of Object.entries(shadows)) {
    lines.push(`  --shadow-${cssKey(name)}: ${value};`);
  }

  lines.push(
    '',
    '  /* Spacing: one unit is one mockup pixel (EF-5). */',
    `  --spacing: ${spacingUnit};`,
    '',
    '  /* Font stacks filled by next/font (EF-3). */',
    '  --font-sans: var(--font-inter), system-ui, sans-serif;',
    '  --font-display: var(--font-space-grotesk), sans-serif;',
    `  --font-mono: ${fontFamilies.mono};`,
    '',
    '  /* Layout (EF-8): the shell breakpoint is a media query, therefore in CSS pixels. */',
    `  --breakpoint-shell: ${String(layout.shellBreakpointPx)}px;`,
    `  --container-sidebar: ${px(layout.sidebarWidthPx)};`,
    `  --container-content: ${px(layout.contentMaxPx)};`,
    `  --container-popover: ${px(layout.popoverWidthPx)};`,
    `  --container-menu: ${px(layout.menuWidthPx)};`,
    '}',
    '',
    '/* Control heights are not a Tailwind namespace; they are consumed through @learny/ui/tokens. */',
    `/* ${controlHeightsPx.join(', ')} mockup px. */`,
    '',
  );

  return lines.join('\n');
}

export function writeThemeCss(): void {
  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, buildThemeCss(), 'utf8');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeThemeCss();
  console.log(`theme.css généré (${path.relative(ROOT, TARGET)})`);
}
