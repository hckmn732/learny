#!/usr/bin/env node
// Generates `src/prompts.generated.ts` from the versioned Markdown prompts (SPEC-508 ET-3).
// The Markdown files are the source of truth; the generated module lets Next and Vitest bundle
// the instructions without reading the filesystem at runtime. Run `pnpm --filter @learny/tutor
// prompts:build` after any prompt change; a unit test asserts the two forms stay identical.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const promptsDir = path.join(root, 'prompts');
const outFile = path.join(root, 'src', 'prompts.generated.ts');

const TASKS = ['programme', 'course', 'tutor'];

function parsePrompt(file) {
  const raw = fs.readFileSync(file, 'utf8');
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw);
  if (match === null) throw new Error(`${file} : en-tête front matter absent`);
  const header = match[1];
  const content = match[2].trim();
  const version = /^version:\s*(\d+)$/m.exec(header)?.[1];
  const task = /^task:\s*([a-z]+)$/m.exec(header)?.[1];
  if (version === undefined || task === undefined) {
    throw new Error(`${file} : version ou task absente`);
  }
  return { task, version: Number(version), content };
}

const entries = TASKS.map((task) => {
  const parsed = parsePrompt(path.join(promptsDir, `${task}.md`));
  if (parsed.task !== task) throw new Error(`${task}.md : task « ${parsed.task} » incohérente`);
  if (!Number.isInteger(parsed.version) || parsed.version < 1) {
    throw new Error(`${task}.md : version invalide`);
  }
  return [task, parsed];
});

const body = `// Generated by scripts/build-prompts.mjs — do not edit.
// Source: packages/tutor/prompts/<task>.md (front-matter version + English instructions).
export const PROMPT_SOURCES = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;
`;
fs.writeFileSync(outFile, body, 'utf8');
console.log(`prompts générés : ${path.relative(root, outFile)}`);
