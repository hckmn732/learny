"""Effect specifications of the automation definitions (SPEC-2205, ADR-0190 section 1).

A definition never writes: `apply` and `undo` return the effects the use case executes inside its
own transaction. Each specification is pure data, built from the payload of the journal row and the
injected instant; the caller generates the identifiers (`gen_random_uuid()` in SQL) and writes them
back to the payload through `assign_payload` / `assign_undo`. No IO and no clock in this module.
"""

from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Any, Final


@dataclass(frozen=True, slots=True)
class InsertSlot:
    """One `schedule_slots` row added by an automation."""

    formation_id: str | None
    kind: str
    title: str
    starts_at: str
    ends_at: str
    module_id: str | None = None
    activity_id: str | None = None
    meta: str | None = None
    created_by: str = "automation"
    planner_key: str | None = None
    status: str = "planned"
    assign_payload: str | None = None
    assign_undo: str | None = None


@dataclass(frozen=True, slots=True)
class CancelSlot:
    """One existing slot switched to `cancelled`, only when the guard holds."""

    slot_id: str
    kind: str | None = None
    only_planned: bool = True
    after: str | None = None


@dataclass(frozen=True, slots=True)
class CancelSprintSlots:
    """EF-3 of the sprint: cancel the future sprints of one milestone only."""

    formation_id: str
    exam_slot_id: str


@dataclass(frozen=True, slots=True)
class InsertActivity:
    """One `activities` row (`warmup`, `remediation`, `exercise`) added by an automation."""

    formation_id: str
    module_id: str
    kind: str
    config: Mapping[str, Any]
    items: tuple[Mapping[str, Any], ...]
    for_date: str
    status: str = "ready"
    assign_payload: str | None = None
    assign_undo: str | None = None


@dataclass(frozen=True, slots=True)
class UpdateActivityStatus:
    """One `activities` row switched to a final status."""

    activity_id: str
    status: str
    only_status: str | None = None
    require_unanswered: bool = False


@dataclass(frozen=True, slots=True)
class ReplaceMissedSlot:
    """A missed session marked `moved`, replaced by a copy at the chosen instant."""

    missed_slot_id: str
    starts_at: str
    ends_at: str
    assign_undo: str | None = None


@dataclass(frozen=True, slots=True)
class RestoreReplacedSlot:
    """The undo of a replacement: cancel the copy and put the missed session back to `planned`."""

    created_slot_id: str
    missed_slot_id: str


@dataclass(frozen=True, slots=True)
class InsertRecallCard:
    """One `recall_card` brick plus its first version (SPEC-717, ADR-0193 section 2)."""

    formation_id: str
    notion_id: str
    front: str
    back: str
    source_label: str
    fingerprint: str | None = None
    assign_payload: str | None = None
    assign_undo: str | None = None


@dataclass(frozen=True, slots=True)
class RetireBrick:
    """One brick retired from the future draws, never deleted."""

    brick_id: str


@dataclass(frozen=True, slots=True)
class EnsureNotionInReview:
    """`notion_states` entered review with a fresh FSRS card due at the local start of day."""

    notion_id: str
    due_at: str
    fsrs: Mapping[str, Any]


@dataclass(frozen=True, slots=True)
class MarkNotificationRead:
    """EF-9: the proposal leaves the in-app inbox as soon as it is cancelled."""

    dedupe_key: str


@dataclass(frozen=True, slots=True)
class EndPause:
    """The `pause_ended` effect: resume the paused formations and draw the diagnostic."""

    pause_id: str


Effect = (
    InsertSlot
    | CancelSlot
    | CancelSprintSlots
    | InsertActivity
    | UpdateActivityStatus
    | ReplaceMissedSlot
    | RestoreReplacedSlot
    | InsertRecallCard
    | RetireBrick
    | EnsureNotionInReview
    | MarkNotificationRead
    | EndPause
)

EFFECT_KEYS: Final = frozenset(
    {
        "slot",
        "activity",
        "brick",
    }
)


@dataclass(frozen=True, slots=True)
class EffectAssignments:
    """Identifiers generated by the executor, placed into the payload or the undo payload."""

    payload: Mapping[str, Any] = field(default_factory=dict)
    undo: Mapping[str, Any] = field(default_factory=dict)


