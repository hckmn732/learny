"""Execution of the effect specifications inside the transaction of the engine (SPEC-2205).

The definitions of `domain/automations/definitions/` decide; this module is the only writer. It runs
inside the learner's RLS transaction when the learner decides, and inside the service transaction
when the engine applies a non-consent proposal. Every identifier generated by the database is handed
back through `EffectAssignments`.
"""

import json
from typing import Any

from sqlalchemy import text

from learny.engagement.domain.automations.effects import (
    CancelSlot,
    CancelSprintSlots,
    EffectAssignments,
    EndPause,
    EnsureNotionInReview,
    InsertActivity,
    InsertRecallCard,
    InsertSlot,
    MarkNotificationRead,
    ReplaceMissedSlot,
    RestoreReplacedSlot,
    RetireBrick,
    UpdateActivityStatus,
)
from learny.shared.errors import AppError
from learny.shared.locale_fr import engagement_automations as fr

INSERT_SLOT = text(
    "insert into public.schedule_slots (user_id, formation_id, module_id, activity_id, kind, title, "
    "meta, starts_at, ends_at, status, created_by, planner_key) values "
    "(cast(:user_id as uuid), cast(:formation_id as uuid), cast(:module_id as uuid), "
    "cast(:activity_id as uuid), cast(:kind as public.slot_kind), :title, :meta, "
    "cast(:starts_at as timestamptz), cast(:ends_at as timestamptz), cast(:status as public.slot_status), "
    "cast(:created_by as public.slot_creator), :planner_key) returning id::text as id"
)

CANCEL_SLOT = text(
    "update public.schedule_slots set status = 'cancelled', updated_at = :now "
    "where id = cast(:slot_id as uuid) and user_id = cast(:user_id as uuid) "
    "and (cast(:kind as text) is null or kind::text = cast(:kind as text)) "
    "and (cast(:only_planned as boolean) is false or status = 'planned') "
    "and (cast(:after as timestamptz) is null or starts_at > cast(:after as timestamptz))"
)

CANCEL_SPRINT_SLOTS = text(
    "update public.schedule_slots set status = 'cancelled', updated_at = :now "
    "where user_id = cast(:user_id as uuid) and formation_id = cast(:formation_id as uuid) "
    "and kind = 'sprint' and status = 'planned' and planner_key like :pattern"
)

INSERT_ACTIVITY = text(
    "insert into public.activities (owner_id, formation_id, module_id, kind, config, items, status, "
    "for_date, created_at) values (cast(:user_id as uuid), cast(:formation_id as uuid), "
    "cast(:module_id as uuid), cast(:kind as public.activity_kind), cast(:config as jsonb), "
    "cast(:items as jsonb), cast(:status as public.activity_status), cast(:for_date as date), "
    "cast(:created_at as timestamptz)) returning id::text as id"
)

COUNT_ANSWERS = text(
    "select count(*)::int as n from public.answers a join public.attempts t on t.id = a.attempt_id "
    "where t.user_id = cast(:user_id as uuid) and t.activity_id = cast(:activity_id as uuid)"
)

UPDATE_ACTIVITY = text(
    "update public.activities set status = cast(:status as public.activity_status) "
    "where id = cast(:activity_id as uuid) and owner_id = cast(:user_id as uuid) "
    "and (cast(:only_status as text) is null or status::text = cast(:only_status as text))"
)

INSERT_BRICK = text(
    "insert into public.bricks (owner_id, formation_id, type, notion_ids, purpose, status, "
    "current_version, created_at) values (cast(:user_id as uuid), cast(:formation_id as uuid), "
    "'recall_card', array[cast(:notion_id as uuid)], 'review', 'active', 1, :now) returning id::text as id"
)

INSERT_BRICK_VERSION = text(
    "insert into public.brick_versions (brick_id, version, payload, fingerprint, origin, created_by, "
    "created_at) values (cast(:brick_id as uuid), 1, cast(:payload as jsonb), :fingerprint, 'tutor', "
    "'tutor', :now)"
)

RETIRE_BRICK = text(
    "update public.bricks set status = 'retired' where id = cast(:brick_id as uuid) "
    "and owner_id = cast(:user_id as uuid)"
)

UPSERT_NOTION_STATE = text(
    "insert into public.notion_states (user_id, notion_id, fsrs, due_at, mastery, first_seen_at, "
    "last_seen_at, success_count, in_review, revision) values (cast(:user_id as uuid), "
    "cast(:notion_id as uuid), cast(:fsrs as jsonb), cast(:due_at as timestamptz), 0, null, null, 0, "
    "true, 0) on conflict (user_id, notion_id) do update set in_review = true, "
    "due_at = case when notion_states.in_review then notion_states.due_at else excluded.due_at end, "
    "fsrs = case when notion_states.in_review then notion_states.fsrs else excluded.fsrs end, "
    "revision = notion_states.revision + 1"
)

MARK_NOTIFICATION_READ = text(
    "update public.notifications set read_at = :now where user_id = cast(:user_id as uuid) "
    "and dedupe_key = :dedupe_key and read_at is null"
)

READ_SLOT_FOR_REPLACEMENT = text(
    "select id::text as id, formation_id::text as formation_id, module_id::text as module_id, "
    "activity_id::text as activity_id, kind::text as kind, title, meta, status::text as status "
    "from public.schedule_slots where id = cast(:slot_id as uuid) and user_id = cast(:user_id as uuid) "
    "for update"
)

MARK_SLOT_MOVED = text(
    "update public.schedule_slots set status = 'moved', updated_at = :now "
    "where id = cast(:slot_id as uuid) and user_id = cast(:user_id as uuid)"
)

RESTORE_SLOT = text(
    "update public.schedule_slots set status = 'planned', updated_at = :now "
    "where id = cast(:slot_id as uuid) and user_id = cast(:user_id as uuid)"
)

INSERT_REPLACEMENT = text(
    "insert into public.schedule_slots (user_id, formation_id, module_id, activity_id, kind, title, "
    "meta, starts_at, ends_at, status, created_by, moved_from_id) values "
    "(cast(:user_id as uuid), cast(:formation_id as uuid), cast(:module_id as uuid), "
    "cast(:activity_id as uuid), cast(:kind as public.slot_kind), :title, :meta, "
    "cast(:starts_at as timestamptz), cast(:ends_at as timestamptz), 'planned', "
    "cast(:created_by as public.slot_creator), cast(:moved_from_id as uuid)) returning id::text as id"
)


async def _apply_one(tx: Any, user_id: str, now: Any, effect: Any) -> dict[str, Any]:
    """Runs one effect and returns its generated identifiers, keyed by their logical name."""
    params: dict[str, Any] = {"user_id": user_id, "now": now}
    if isinstance(effect, InsertSlot):
        result = await tx.conn.execute(
            INSERT_SLOT,
            {
                **params,
                "formation_id": effect.formation_id,
                "module_id": effect.module_id,
                "activity_id": effect.activity_id,
                "kind": effect.kind,
                "title": effect.title,
                "meta": effect.meta,
                "starts_at": effect.starts_at,
                "ends_at": effect.ends_at,
                "status": effect.status,
                "created_by": effect.created_by,
                "planner_key": effect.planner_key,
            },
        )
        row = result.mappings().one()
        assigned: dict[str, Any] = {}
        if effect.assign_payload is not None:
            assigned[f"payload:{effect.assign_payload}"] = row["id"]
        if effect.assign_undo is not None:
            assigned[f"undo:{effect.assign_undo}"] = row["id"]
        return assigned
    if isinstance(effect, CancelSlot):
        await tx.conn.execute(
            CANCEL_SLOT,
            {
                **params,
                "slot_id": effect.slot_id,
                "kind": effect.kind,
                "only_planned": effect.only_planned,
                "after": effect.after,
            },
        )
        return {}
    if isinstance(effect, CancelSprintSlots):
        await tx.conn.execute(
            CANCEL_SPRINT_SLOTS,
            {
                **params,
                "formation_id": effect.formation_id,
                "pattern": f"sprint:{effect.exam_slot_id}:%",
            },
        )
        return {}
    if isinstance(effect, InsertActivity):
        result = await tx.conn.execute(
            INSERT_ACTIVITY,
            {
                **params,
                "formation_id": effect.formation_id,
                "module_id": effect.module_id,
                "kind": effect.kind,
                "config": json.dumps(dict(effect.config), ensure_ascii=False),
                "items": json.dumps([dict(item) for item in effect.items], ensure_ascii=False),
                "status": effect.status,
                "for_date": effect.for_date,
                "created_at": now,
            },
        )
        row = result.mappings().one()
        assigned = {}
        if effect.assign_payload is not None:
            assigned[f"payload:{effect.assign_payload}"] = row["id"]
        if effect.assign_undo is not None:
            assigned[f"undo:{effect.assign_undo}"] = row["id"]
        return assigned
    if isinstance(effect, UpdateActivityStatus):
        if effect.require_unanswered:
            count = await tx.conn.execute(
                COUNT_ANSWERS, {"user_id": user_id, "activity_id": effect.activity_id}
            )
            if int(count.mappings().one()["n"]) > 0:
                raise AppError("AUTOMATION_ACTION_CONSUMED", fr.WARMUP_STARTED)
        await tx.conn.execute(
            UPDATE_ACTIVITY,
            {
                **params,
                "activity_id": effect.activity_id,
                "status": effect.status,
                "only_status": effect.only_status,
            },
        )
        return {}
    if isinstance(effect, ReplaceMissedSlot):
        result = await tx.conn.execute(
            READ_SLOT_FOR_REPLACEMENT, {"user_id": user_id, "slot_id": effect.missed_slot_id}
        )
        missed = result.mappings().first()
        if missed is None:
            raise AppError("NOT_FOUND", fr.MISSED_SLOT_NOT_FOUND)
        if missed["status"] == "moved":
            raise AppError("CONFLICT", fr.MISSED_SLOT_ALREADY_MOVED)
        await tx.conn.execute(
            MARK_SLOT_MOVED, {"now": now, "slot_id": effect.missed_slot_id, "user_id": user_id}
        )
        inserted = await tx.conn.execute(
            INSERT_REPLACEMENT,
            {
                **params,
                "formation_id": missed["formation_id"],
                "module_id": missed["module_id"],
                "activity_id": missed["activity_id"],
                "kind": missed["kind"],
                "title": missed["title"],
                "meta": missed["meta"],
                "starts_at": effect.starts_at,
                "ends_at": effect.ends_at,
                "created_by": "automation",
                "moved_from_id": effect.missed_slot_id,
            },
        )
        created = inserted.mappings().one()["id"]
        assigned = {}
        if effect.assign_undo is not None:
            assigned[f"undo:{effect.assign_undo}"] = created
        return assigned
    if isinstance(effect, RestoreReplacedSlot):
        await tx.conn.execute(
            CANCEL_SLOT,
            {
                **params,
                "slot_id": effect.created_slot_id,
                "kind": None,
                "only_planned": True,
                "after": None,
            },
        )
        await tx.conn.execute(
            RESTORE_SLOT, {"now": now, "slot_id": effect.missed_slot_id, "user_id": user_id}
        )
        return {}
    if isinstance(effect, InsertRecallCard):
        result = await tx.conn.execute(
            INSERT_BRICK,
            {
                **params,
                "formation_id": effect.formation_id,
                "notion_id": effect.notion_id,
            },
        )
        brick_id = result.mappings().one()["id"]
        await tx.conn.execute(
            INSERT_BRICK_VERSION,
            {
                **params,
                "brick_id": brick_id,
                "payload": json.dumps(
                    {
                        "front": effect.front,
                        "back": effect.back,
                        "sourceLabel": effect.source_label,
                        "sources": [],
                    },
                    ensure_ascii=False,
                ),
                "fingerprint": effect.fingerprint,
            },
        )
        assigned = {}
        if effect.assign_payload is not None:
            assigned[f"payload:{effect.assign_payload}"] = brick_id
        if effect.assign_undo is not None:
            assigned[f"undo:{effect.assign_undo}"] = brick_id
        return assigned
    if isinstance(effect, RetireBrick):
        await tx.conn.execute(RETIRE_BRICK, {"user_id": user_id, "brick_id": effect.brick_id})
        return {}
    if isinstance(effect, EnsureNotionInReview):
        await tx.conn.execute(
            UPSERT_NOTION_STATE,
            {
                **params,
                "notion_id": effect.notion_id,
                "fsrs": json.dumps(dict(effect.fsrs), ensure_ascii=False),
                "due_at": effect.due_at,
            },
        )
        return {}
    if isinstance(effect, MarkNotificationRead):
        await tx.conn.execute(
            MARK_NOTIFICATION_READ,
            {"now": now, "user_id": user_id, "dedupe_key": effect.dedupe_key},
        )
        return {}
    if isinstance(effect, EndPause):
        from learny.engagement.application import pause as pause_service

        return await pause_service.end_pause_effect(tx, user_id=user_id, pause_id=effect.pause_id, now=now)
    raise AppError("INTERNAL_ERROR", f"Unknown automation effect: {type(effect).__name__}")


async def apply_effects(tx: Any, *, user_id: str, now: Any, effects: tuple[Any, ...]) -> EffectAssignments:
    """Runs every effect in order and collects the identifiers of the assignments."""
    payload: dict[str, Any] = {}
    undo: dict[str, Any] = {}
    for effect in effects:
        assigned = await _apply_one(tx, user_id, now, effect)
        for key, value in assigned.items():
            scope, _, name = key.partition(":")
            if scope == "payload":
                payload[name] = value
            else:
                undo[name] = value
    return EffectAssignments(payload=payload, undo=undo)


__all__ = ["apply_effects"]
